#!/usr/bin/env python3
"""Generate `src/deid/e1_1.rs` from the DICOM standard's PS3.15 Table E.1-1.

Source: https://dicom.nema.org/medical/dicom/current/output/chtml/part15/chapter_E.html
Usage:  python3 scripts/gen_e1_1.py [output-path]

Emits one row per attribute: the Basic Profile action plus the non-empty option
actions. Ambiguous cells (`X/Z`, `X/Z/D`, ...) are collapsed to a single action,
preferring `Z` (keeps the element present, valid for Type 1/2 attributes), then
`D`, `U`, `X`, `K`, `C`. Attributes with an empty `Basic Prof.` are skipped
(they are kept unless an option says otherwise — E.1-1 has none such today).

Option columns, in table order (this is also the resolution precedence):
  rtn_safe_priv, rtn_uids, rtn_dev_id, rtn_inst_id, rtn_pat_chars,
  rtn_long_full_dates, rtn_long_modif_dates,
  clean_desc, clean_struct, clean_graph
"""
import collections
import html
import re
import sys
import urllib.request

URL = "https://dicom.nema.org/medical/dicom/current/output/chtml/part15/chapter_E.html"
DEFAULT_OUT = "src/deid/e1_1.rs"

OPTIONS = [
    ("Rtn. Safe Priv. Opt.", "rtn_safe_priv"),
    ("Rtn. UIDs Opt.", "rtn_uids"),
    ("Rtn. Dev. Id. Opt.", "rtn_dev_id"),
    ("Rtn. Inst. Id. Opt.", "rtn_inst_id"),
    ("Rtn. Pat. Chars. Opt.", "rtn_pat_chars"),
    ("Rtn. Long. Full Dates Opt.", "rtn_long_full_dates"),
    ("Rtn. Long. Modif. Dates Opt.", "rtn_long_modif_dates"),
    ("Clean Desc. Opt.", "clean_desc"),
    ("Clean Struct. Cont. Opt.", "clean_struct"),
    ("Clean Graph. Opt.", "clean_graph"),
]

VALID = ("X", "Z", "D", "U", "K", "C")


def cell(td: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", td)).replace("\u200b", "").strip()


def one_line(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def cells(row: str):
    return [cell(x) for x in re.findall(r"<t[dh]\b.*?</t[dh]>", row, re.S | re.I)]


def map_action(v: str):
    v = v.strip().replace("*", "").replace("\\", "/")
    if not v:
        return None
    parts = [p.strip() for p in v.split("/") if p.strip()]
    if len(parts) == 1 and parts[0] in VALID:
        return parts[0]
    for pref in ("Z", "D", "U", "X", "K", "C"):
        if pref in parts:
            return pref
    return None


def main() -> int:
    out_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    raw = urllib.request.urlopen(URL, timeout=90).read().decode("utf-8", "replace")

    target = None
    for t in re.findall(r"<table\b.*?</table>", raw, re.S | re.I):
        if "Basic Prof" in t and "Attribute Name" in t:
            target = t
            break
    if target is None:
        print("error: Table E.1-1 not found", file=sys.stderr)
        return 2

    rows = re.findall(r"<tr\b.*?</tr>", target, re.S | re.I)
    header = cells(rows[0])
    idx_basic = header.index("Basic Prof.")
    idx_opt = [header.index(name) for name, _ in OPTIONS]

    seen, order, skipped, dist = {}, [], [], collections.Counter()
    for r in rows[1:]:
        c = cells(r)
        if len(c) <= max(idx_opt):
            continue
        name, tagtxt, basic = c[0], c[1], c[idx_basic]
        m = re.search(r"\(([0-9A-Fa-f]{4}),([0-9A-Fa-f]{4})\)", tagtxt)
        if not m:
            if name and tagtxt:
                skipped.append(tagtxt)
            continue
        act = map_action(basic)
        dist[one_line(basic) or "<empty>"] += 1
        if act is None:
            continue
        opts = []
        for (opt_name, key), idx in zip(OPTIONS, idx_opt):
            oa = map_action(c[idx])
            if oa is not None:
                opts.append((key, oa))
        key = (int(m.group(1), 16), int(m.group(2), 16))
        if key not in seen:
            order.append(key)
        seen[key] = (one_line(name), act, opts)

    lines = [
        "//! PS3.15 Table E.1-1 — Basic Application Level Confidentiality Profile",
        "//! plus the option columns.",
        "//!",
        "//! GENERATED by `scripts/gen_e1_1.py` from the DICOM standard",
        "//! (part15/chapter_E.html). Do not edit by hand. Each row is",
        "//! `(tag, basic_action, &[(option_key, action)])`; the trailing comment is",
        "//! the attribute name. Ambiguous cells (e.g. `X/Z`) are collapsed to one",
        "//! action (preferring `Z`, then D/U/X/K/C). Option keys are resolved in",
        "//! slice order (later wins); see `profile.rs`.",
        "",
        "use crate::config::Action;",
        "",
        "pub const E11: &[(&str, Action, &[(&str, Action)])] = &[",
    ]
    for g, e in order:
        name, act, opts = seen[(g, e)]
        if opts:
            opt_src = ", ".join(f'("{k}", Action::{a})' for k, a in opts)
            opt_src = f"&[{opt_src}]"
        else:
            opt_src = "&[]"
        lines.append(f'    ("{g:04X},{e:04X}", Action::{act}, {opt_src}), // {name}')
    lines += ["];", ""]

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"wrote {out_path}: {len(seen)} attributes")
    print("raw Basic Prof. distribution:", dict(dist))
    print(f"skipped wildcard rows: {len(skipped)} -> {skipped}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
