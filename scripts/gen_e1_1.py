#!/usr/bin/env python3
"""Generate `src/deid/e1_1.rs` from the DICOM standard's PS3.15 Table E.1-1.

Source: https://dicom.nema.org/medical/dicom/current/output/chtml/part15/chapter_E.html
Usage:  python3 scripts/gen_e1_1.py [output-path]

Only the `Basic Prof.` column is used. Ambiguous cells (`X/Z`, `X/Z/D`, ...)
are collapsed to a single action, preferring `Z` (keeps the element present,
which stays valid for Type 1/2 attributes), then `D`, `U`, `X`, `K`, `C`.
Option-only rows (empty `Basic Prof.`) are skipped: the attribute is kept.
"""
import collections
import html
import re
import sys
import urllib.request

URL = "https://dicom.nema.org/medical/dicom/current/output/chtml/part15/chapter_E.html"
DEFAULT_OUT = "src/deid/e1_1.rs"


def cell(td: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", td)).replace("\u200b", "").strip()


def one_line(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def cells(row: str):
    return [cell(x) for x in re.findall(r"<t[dh]\b.*?</t[dh]>", row, re.S | re.I)]


def map_action(v: str):
    v = v.strip().replace("*", "").replace("\\", "/")
    if not v:
        return None, v
    parts = [p.strip() for p in v.split("/") if p.strip()]
    if len(parts) == 1 and parts[0] in ("X", "Z", "D", "U", "K", "C"):
        return parts[0], v
    for pref in ("Z", "D", "U", "X", "K", "C"):
        if pref in parts:
            return pref, v
    return None, v


def main() -> int:
    out_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    raw = urllib.request.urlopen(URL, timeout=90).read().decode("utf-8", "replace")

    target = None
    for t in re.findall(r"<table\b.*?</table>", raw, re.S | re.I):
        if "Basic Prof" in t and "Attribute Name" in t:
            target = t
            break
    if target is None:
        print("error: Table E.1-1 not found", file=sys.stderr)
        return 2

    rows = re.findall(r"<tr\b.*?</tr>", target, re.S | re.I)
    header = cells(rows[0])
    idx_basic = header.index("Basic Prof.")

    seen, order, skipped, dist = {}, [], [], collections.Counter()
    for r in rows[1:]:
        c = cells(r)
        if len(c) <= idx_basic:
            continue
        name, tagtxt, basic = c[0], c[1], c[idx_basic]
        m = re.search(r"\(([0-9A-Fa-f]{4}),([0-9A-Fa-f]{4})\)", tagtxt)
        if not m:
            if name and tagtxt:
                skipped.append((name, tagtxt))
            continue
        act, rawv = map_action(basic)
        dist[rawv or "<empty>"] += 1
        if act is None:
            continue
        key = (int(m.group(1), 16), int(m.group(2), 16))
        if key not in seen:
            order.append(key)
        seen[key] = (name, act, rawv)

    lines = [
        "//! PS3.15 Table E.1-1 — Basic Application Level Confidentiality Profile.",
        "//!",
        "//! GENERATED by `scripts/gen_e1_1.py` from the DICOM standard",
        "//! (part15/chapter_E.html). Do not edit by hand. The trailing comment is",
        "//! the raw `Basic Prof.` cell; ambiguous cells (e.g. `X/Z`) are collapsed",
        "//! to one action (preferring `Z`, then D/U/X/K/C).",
        "",
        "use crate::config::Action;",
        "",
        "pub const E11_BASE: &[(&str, Action)] = &[",
    ]
    for g, e in order:
        name, act, rawv = seen[(g, e)]
        comment = one_line(name) if rawv == act else one_line(f"{name} [{rawv}]")
        lines.append(f'    ("{g:04X},{e:04X}", Action::{act}), // {comment}')
    lines += ["];", ""]

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"wrote {out_path}: {len(seen)} attributes")
    print("raw Basic Prof. distribution:", dict(dist))
    print(f"skipped wildcard rows: {len(skipped)} -> {[s[1] for s in skipped]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
